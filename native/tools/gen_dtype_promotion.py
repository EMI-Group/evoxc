#!/usr/bin/env python3
"""Generate the native dtype promotion table from numpy.

Dev aid only: the emitted Rust file is committed and authoritative
(`native/CONTEXT.md`).  Re-run when the evoxc dtype set changes:

    source scripts/dev-env.sh && .venv/bin/python native/tools/gen_dtype_promotion.py

Why a set-based table: ``np.result_type`` is not associative under pairwise
folding (``result_type(int8, uint8, float16) == float16`` while pairwise gives
``float32``) but depends only on the SET of input dtypes (verified over all
16384 subsets, with order and duplicate permutations).  The table below is
exact by construction for every subset, so ``promote_all`` matches numpy for
any operand count.
"""

from __future__ import annotations

import argparse
import pathlib
import random
import sys

import numpy as np

#: Fixed dtype order; bit i of the mask is DTYPE_NAMES[i].  Must match
#: ``DType::index()`` in ``evoxc-core/src/dtype.rs``.
DTYPE_NAMES = [
    "bool",
    "int8",
    "int16",
    "int32",
    "int64",
    "uint8",
    "uint16",
    "uint32",
    "uint64",
    "float16",
    "float32",
    "float64",
    "complex64",
    "complex128",
]

DEFAULT_OUT = "native/evoxc-core/src/dtype_table.rs"


def build_table() -> tuple[list[int], list[tuple[str, str, str]]]:
    dtypes = [np.dtype(name) for name in DTYPE_NAMES]
    table: list[int] = [0] * (1 << len(dtypes))
    for mask in range(1, 1 << len(dtypes)):
        subset = [dtypes[i] for i in range(len(dtypes)) if mask >> i & 1]
        table[mask] = DTYPE_NAMES.index(np.result_type(*subset).name)

    # Exhaustive consistency checks (order, duplicates) and sampled n-ary checks.
    problems: list[tuple[str, str, str]] = []
    for mask in range(1, 1 << len(dtypes)):
        subset = [dtypes[i] for i in range(len(dtypes)) if mask >> i & 1]
        expected = DTYPE_NAMES[table[mask]]
        rng = random.Random(mask)
        for _ in range(2):
            shuffled = subset[:]
            rng.shuffle(shuffled)
            with_dups = shuffled + [rng.choice(subset)]
            rng.shuffle(with_dups)
            for candidate in (shuffled, with_dups):
                got = np.result_type(*candidate).name
                if got != expected:
                    problems.append((",".join(d.name for d in subset), expected, got))
        # sampled 3/4-ary: promotion via the table must match numpy
        for n in (3, 4):
            if len(subset) >= 2:
                picks = [rng.choice(subset) for _ in range(n)]
                mask2 = 0
                for dt in picks:
                    mask2 |= 1 << DTYPE_NAMES.index(dt.name)
                if DTYPE_NAMES[table[mask2]] != np.result_type(*picks).name:
                    problems.append(
                        (
                            ",".join(d.name for d in picks),
                            DTYPE_NAMES[table[mask2]],
                            np.result_type(*picks).name,
                        )
                    )
    return table, problems


def emit(table: list[int]) -> str:
    size = len(table)
    assert size == 1 << len(DTYPE_NAMES)
    # Byte-string literal keeps the file compact: one escape per entry.
    raw = "".join(f"\\x{value:02x}" for value in table)
    chunks = [raw[i : i + 96] for i in range(0, len(raw), 96)]
    # Rust string-continuation escapes: a trailing "\\" strips the newline and
    # the following indentation, so chunks join without whitespace.
    body = "\\\n".join(chunks)
    return f"""// @generated by native/tools/gen_dtype_promotion.py — do not edit by hand.
// Re-run the generator after changing the evoxc dtype set (native/CONTEXT.md).
//
// Entry `mask` (bit i = DType index i) is the index of `np.result_type(...)`
// over the dtype SET encoded by `mask`.  Exact by construction for any
// operand count: numpy promotion is set-based and non-associative pairwise.
//
// Legitimately large and machine-generated: do not split or reformat.

/// `np.result_type` over every non-empty subset of the 14 evoxc dtypes.
pub static PROMOTION_TABLE: [u8; {size}] = *b"\\
{body}";

/// Dtype index order; bit i of a mask refers to `ORDER[i]`.
pub static ORDER: [&str; {len(DTYPE_NAMES)}] = [
{chr(10).join(f'    "{name}",' for name in DTYPE_NAMES)}
];
"""


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="verify the committed file is fresh")
    args = parser.parse_args(argv)

    table, problems = build_table()
    if problems:
        print("gen_dtype_promotion: promotion table is NOT set-based:", file=sys.stderr)
        for line in problems[:10]:
            print("  ", line, file=sys.stderr)
        return 1

    text = emit(table)
    out = pathlib.Path(args.out)
    if args.check:
        current = out.read_text()
        if current != text:
            print(f"gen_dtype_promotion: {out} is stale — re-run the generator", file=sys.stderr)
            return 1
        print(f"gen_dtype_promotion: {out} is fresh")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"gen_dtype_promotion: wrote {out} ({len(table)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
