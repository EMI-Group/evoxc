#!/usr/bin/env python3
"""Generate the native op-schema table from the Python op registry.

Dev aid only: the emitted Rust file is committed and authoritative
(`native/CONTEXT.md`).  Re-run after adding or changing an op:

    source scripts/dev-env.sh && .venv/bin/python native/tools/gen_opdefs.py

The output carries exactly what native code needs to validate an op:
name, category, arity range, result-count range, effect, region count,
terminator flag, whether the Python registry attaches a shape hook, and the
declared attribute schema (with JSON-encoded defaults).
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

DEFAULT_OUT = "native/evoxc-core/src/schema_table.rs"


def rust_str(value: str) -> str:
    """A Rust double-quoted string literal (escapes everything non-ASCII)."""
    out = ['"']
    for ch in value:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{code:x}}}")
    out.append('"')
    return "".join(out)


def json_default(value) -> str | None:
    """JSON text for a default, or None when the value is not JSON-able."""
    try:
        return json.dumps(value, sort_keys=True, separators=(",", ":"))
    except (TypeError, ValueError):
        return None


def arity_bounds(arity) -> tuple[int, str]:
    if isinstance(arity, int):
        return arity, f"Some({arity})"
    lo, hi = arity
    return lo, "None" if hi is None else f"Some({hi})"


def result_bounds(count) -> tuple[str, str, bool]:
    if count is None:
        return "0", "None", "false"
    if isinstance(count, int):
        return str(count), f"Some({count})", "true"
    lo, hi = count
    return str(lo), ("None" if hi is None else f"Some({hi})"), "false"


def emit(opdefs) -> str:
    lines: list[str] = []
    shape_less: list[str] = []
    index: list[tuple[str, int]] = []

    for position, op in enumerate(opdefs):
        index.append((op.name, position))
        arity_min, arity_max = arity_bounds(op.arity)
        result_min, result_max, known = result_bounds(op.result_count)
        if op.shape_fn is None:
            shape_less.append(op.name)
        attrs: list[str] = []
        for attr in op.attributes:
            default = None
            if not attr.required:
                default = json_default(attr.default)
            attrs.append(
                "AttrSchema { name: "
                f"{rust_str(attr.name)}, ty: {rust_str(attr.type)}, required: "
                f"{'true' if attr.required else 'false'}, default_json: "
                f"{'None' if default is None else 'Some(' + rust_str(default) + ')'} }}"
            )
        attr_body = "        attrs: &[]," if not attrs else "        attrs: &[\n" + "\n".join(
            f"            {item}," for item in attrs
        ) + "\n        ],"
        lines.append(
            "\n".join(
                [
                    "    OpSchema {",
                    f"        name: {rust_str(op.name)},",
                    f"        category: {rust_str(op.category)},",
                    f"        arity_min: {arity_min},",
                    f"        arity_max: {arity_max},",
                    f"        result_min: {result_min},",
                    f"        result_max: {result_max},",
                    f"        result_count_known: {known},",
                    f"        effect: {rust_str(op.effect)},",
                    f"        regions: {op.regions},",
                    f"        is_terminator: {'true' if op.is_terminator else 'false'},",
                    f"        has_shape_fn: {'true' if op.shape_fn is not None else 'false'},",
                    attr_body,
                    "    },",
                ]
            )
        )

    sorted_index = sorted(index)
    index_body = "\n".join(f"    ({rust_str(name)}, {pos})," for name, pos in sorted_index)
    return f"""// @generated by native/tools/gen_opdefs.py from evoxc.ir.op_defs.all_opdefs().
// do not edit by hand; re-run the generator (native/CONTEXT.md).
//
// The committed table is authoritative for the native core: schema validation,
// attribute defaults and shape-inference dispatch all read it.

use crate::schema::{{AttrSchema, OpSchema}};

/// Every registered EvoXIR op, in registry order (sorted by name).
pub static OPS: &[OpSchema] = &[
{chr(10).join(lines)}
];

/// `(name, index into OPS)` sorted by name for binary search.
pub static OP_INDEX: &[(&str, u16)] = &[
{index_body}
];

/// Number of registered ops.
pub const OP_COUNT: usize = {len(opdefs)};

/// Ops whose result types are resolved op-specifically (no shape hook).
pub static OP_SPECIFIC_RESULTS: &[&str] = &[
{chr(10).join(f'    {rust_str(name)},' for name in shape_less)}
];
"""


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="verify the committed file is fresh")
    args = parser.parse_args(argv)

    root = pathlib.Path(__file__).resolve().parents[2]
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))

    try:
        from evoxc.ir.op_defs import all_opdefs
    except ImportError as exc:  # pragma: no cover - dev aid
        print(
            "gen_opdefs: cannot import evoxc — run inside the project venv "
            f"(source scripts/dev-env.sh): {exc}",
            file=sys.stderr,
        )
        return 2

    opdefs = list(all_opdefs())
    names = [op.name for op in opdefs]
    if len(set(names)) != len(names):
        print("gen_opdefs: duplicate op names in registry", file=sys.stderr)
        return 1

    text = emit(opdefs)
    out = pathlib.Path(args.out)
    if args.check:
        if out.read_text() != text:
            print(f"gen_opdefs: {out} is stale — re-run the generator", file=sys.stderr)
            return 1
        print(f"gen_opdefs: {out} is fresh ({len(opdefs)} ops)")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"gen_opdefs: wrote {out} ({len(opdefs)} ops)")

    emitted_warnings = sorted({line for line in emit_warnings(opdefs)})
    for line in emitted_warnings:
        print(f"gen_opdefs: warning: {line}", file=sys.stderr)
    return 0


def emit_warnings(opdefs) -> list[str]:
    """Collect non-JSON default warnings without duplicating emit() logic."""
    found: list[str] = []
    for op in opdefs:
        for attr in op.attributes:
            if not attr.required and json_default(attr.default) is None:
                found.append(
                    f"op {op.name}: attribute {attr.name} has a non-JSON default; emitted as absent"
                )
    return found


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
