//! PyO3 binding: the `evoxc._evoxc_native` module.
//!
//! Contract: `native/CONTEXT.md`.  The binding converts one envelope per call
//! and never implements numerical semantics itself — inference is
//! `evoxc_core::infer_op`, transforms are `evoxc-compiler`.
//!
//! Surface (`native/CONTEXT.md` "FFI surface"):
//!
//! * `version() -> str` and `__version__`
//! * `infer(op_name, operand_types, attributes, result_types=None, module=None)`
//! * `transform(kind, module, config)` — `evoxc-compiler`'s five transforms
//! * `NativeError` with `.kind` / `.message`
mod convert;
mod error;
mod module_ops;
mod transform_config;
use pyo3::prelude::*;
/// Native core version (`evoxc._evoxc_native.version()`).
#[pyfunction]
fn version() -> &'static str {
    evoxc_core::VERSION
}
/// Native shape inference: one op's result types from its operand types.
///
/// `operand_types` / `result_types` accept lists or tuples of
/// `{"dtype": str, "shape": [dim, ...]}` dicts.  `module` supplies the callee
/// signatures `call` resolves against and comes in two shapes: a full
/// `evoxc-native-ir` envelope, or the lightweight signature-only context
/// `{"functions": [[name, [output types]], ...]}` (also
/// `[name, [input types], [output types]]` and
/// `{"name": ..., "input_types": ..., "output_types": ...}` entries).
/// `result_types` is needed only by the op-specific ops (`if`, `while`,
/// `runtime_call`, `block_call`, `external_call`).  Arguments are read-only.
#[pyfunction]
#[pyo3(signature = (op_name, operand_types, attributes, result_types=None, module=None))]
fn infer<'py>(
    py: Python<'py>,
    op_name: &str,
    operand_types: &Bound<'py, PyAny>,
    attributes: &Bound<'py, PyAny>,
    result_types: Option<&Bound<'py, PyAny>>,
    module: Option<&Bound<'py, PyAny>>,
) -> PyResult<Py<PyAny>> {
    module_ops::infer(
        py,
        op_name,
        operand_types,
        Some(attributes),
        result_types,
        module,
    )
}
/// Native graph transform (`vectorize` / `vmap` / `grad` / `jvp` / `vjp`).
///
/// Takes one `evoxc-native-ir` envelope, the transform config dict and returns
/// the transformed envelope plus the `"transform"` metadata object.  The
/// engines live in `evoxc-compiler`.
#[pyfunction]
fn transform(
    py: Python<'_>,
    kind: &str,
    module: &Bound<'_, PyAny>,
    config: &Bound<'_, PyAny>,
) -> PyResult<Py<PyAny>> {
    module_ops::transform(py, kind, module, config)
}
#[pymodule]
fn _evoxc_native(module: &Bound<'_, PyModule>) -> PyResult<()> {
    let py = module.py();
    // `__all__` is generated by `#[pymodule]` from the module's own content;
    // do not add it twice.
    module.add("__version__", evoxc_core::VERSION)?;
    let native_error = py.get_type::<error::NativeError>();
    native_error.setattr("__module__", "evoxc._evoxc_native")?;
    module.add("NativeError", native_error)?;
    module.add_function(wrap_pyfunction!(version, module)?)?;
    module.add_function(wrap_pyfunction!(infer, module)?)?;
    module.add_function(wrap_pyfunction!(transform, module)?)?;
    Ok(())
}
