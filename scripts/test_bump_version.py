class NormalizeVersionTests(unittest.TestCase):
    def test_accepts_bare_and_prefixed_versions(self):
        self.assertEqual(bump_version.normalize_version("0.2.0"), "0.2.0")
        self.assertEqual(bump_version.normalize_version("v0.2.0"), "0.2.0")
        self.assertEqual(bump_version.normalize_version("V1.2.3"), "1.2.3")

    def test_strips_surrounding_whitespace(self):
        self.assertEqual(bump_version.normalize_version("  v0.2.0\n"), "0.2.0")
        self.assertEqual(bump_version.normalize_version("\t1.2.3 "), "1.2.3")

    def test_accepts_pep440_style_suffixes(self):
        for candidate in ("1.2.3-rc1", "1.2.3.post1", "1.2.3+local", "1.2.3rc1"):
            self.assertEqual(bump_version.normalize_version(candidate), candidate)
            self.assertEqual(
                bump_version.normalize_version("v" + candidate), candidate
            )

    def test_rejects_malformed_versions(self):
        for candidate in ("1.2", "v", "V", "abc", "1.2.3 4", "", "   ", "1.2.3-", "1.2.x"):
            with self.subTest(candidate=candidate):
                with self.assertRaises(ValueError):
                    bump_version.normalize_version(candidate)

    def test_tag_for(self):
        self.assertEqual(bump_version.tag_for("0.2.0"), "v0.2.0")


