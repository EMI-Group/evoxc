class ChangelogPatchTests(unittest.TestCase):
    def test_releases_unreleased_and_opens_a_fresh_one(self):
        updated, edits = bump_version.patch_changelog(
            FIXTURE_CHANGELOG, "0.2.0", "2026-11-25"
        )
        self.assertIn(
            "## [Unreleased]\n\n## [0.2.0] - 2026-11-25\n### Added\n- A brand new thing.\n",
            updated,
        )
        self.assertNotIn("## [Unreleased]\n### Added", updated)
        self.assertIn("## [0.1.0] - 2026-10-29", updated)
        self.assertEqual(
            [edit.key for edit in edits], ["heading", "link reference"]
        )
        self.assertEqual(
            edits[0].old, "## [Unreleased]"
        )
        self.assertEqual(edits[0].new, "## [0.2.0] - 2026-11-25")

    def test_inserts_link_reference_before_the_existing_one(self):
        updated, _ = bump_version.patch_changelog(
            FIXTURE_CHANGELOG, "0.2.0", date(2026, 11, 25)
        )
        self.assertTrue(
            updated.endswith(
                "[0.2.0]: https://github.com/EMI-Group/evoxc/releases/tag/v0.2.0\n"
                "[0.1.0]: https://github.com/EMI-Group/evoxc/releases/tag/v0.1.0\n"
            )
        )

    def test_is_idempotent_and_never_duplicates(self):
        once, _ = bump_version.patch_changelog(FIXTURE_CHANGELOG, "0.2.0", "2026-11-25")
        twice, edits = bump_version.patch_changelog(once, "0.2.0", "2026-11-26")
        self.assertEqual(twice, once)
        self.assertEqual(edits, [])
        self.assertEqual(once.count("## [0.2.0]"), 1)
        self.assertEqual(once.count("[0.2.0]:"), 1)
        self.assertEqual(once.count("## [Unreleased]"), 1)

    def test_inserts_a_section_when_there_is_no_unreleased(self):
        text = (
            "# Changelog\n"
            "Intro line.\n"
            "## [0.1.0] - 2026-10-29\n"
            "First release.\n"
            "[0.1.0]: https://github.com/EMI-Group/evoxc/releases/tag/v0.1.0\n"
        )
        updated, edits = bump_version.patch_changelog(text, "0.2.0", "2026-11-25")
        self.assertIn(
            "Intro line.\n## [0.2.0] - 2026-11-25\n\n## [0.1.0] - 2026-10-29\n", updated
        )
        self.assertNotIn("## [Unreleased]", updated)
        self.assertEqual(edits[0].old, "(none)")

    def test_appends_the_link_reference_when_none_exists(self):
        text = "# Changelog\nIntro.\n## [Unreleased]\n- pending\n"
        updated, _ = bump_version.patch_changelog(text, "0.2.0", "2026-11-25")
        self.assertTrue(
            updated.endswith(
                "[0.2.0]: https://github.com/EMI-Group/evoxc/releases/tag/v0.2.0\n"
            )
        )

    def test_appends_a_heading_to_a_bare_preamble(self):
        updated, _ = bump_version.patch_changelog(
            "# Changelog\nIntro without sections.\n", "0.2.0", "2026-11-25"
        )
        self.assertIn(
            "Intro without sections.\n\n## [0.2.0] - 2026-11-25\n", updated
        )

    def test_rejects_an_invalid_date(self):
        with self.assertRaises(bump_version.BumpError):
            bump_version.patch_changelog(FIXTURE_CHANGELOG, "0.2.0", "25-11-2026")


