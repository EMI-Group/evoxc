    def test_push_publishes_branch_and_tag_atomically(self):
        remote_tmp = tempfile.TemporaryDirectory()
        self.addCleanup(remote_tmp.cleanup)
        remote = Path(remote_tmp.name) / "origin.git"
        _git(self.root, "init", "--bare", "--quiet", str(remote))
        _git(self.root, "remote", "add", "origin", str(remote))

        code, stdout, stderr = self.run_main("0.2.0", "--yes")

        self.assertEqual(code, 0, stdout + stderr)
        self.assertIn("pushed branch main and tag v0.2.0 to origin", stdout)
        self.assertEqual(
            _git(remote, "rev-parse", "refs/heads/main").stdout.strip(), self.rev("HEAD")
        )
        self.assertEqual(_git(remote, "cat-file", "-t", "refs/tags/v0.2.0").stdout.strip(), "tag")
        self.assertEqual(
            _git(remote, "rev-parse", "refs/tags/v0.2.0^{commit}").stdout.strip(),
            self.rev("HEAD"),
        )

