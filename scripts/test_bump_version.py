def _run(cmd, cwd, check=True):
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if check and result.returncode != 0:
        raise AssertionError(
            f"{cmd} failed ({result.returncode}):\n{result.stdout}\n{result.stderr}"
        )
    return result


def _git(root, *args, check=True):
    return _run(["git", *args], root, check=check)


class _NotATty(io.StringIO):
    """A stdin stand-in that reports itself as non-interactive."""

    def isatty(self) -> bool:  # noqa: D102 - io.StringIO subclass
        return False


class RepoTestCase(unittest.TestCase):
    """A throwaway git repository with the fixture tree committed."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        previous = os.getcwd()
        self.addCleanup(os.chdir, previous)
        os.chdir(self.root)

        for relative, content in FIXTURE_FILES.items():
            path = self.root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="")

        _git(self.root, "init", "--quiet")
        _git(self.root, "symbolic-ref", "HEAD", "refs/heads/main")
        _git(self.root, "config", "user.email", "release@example.invalid")
        _git(self.root, "config", "user.name", "Release Bot")
        _git(self.root, "config", "commit.gpgsign", "false")
        _git(self.root, "config", "tag.gpgsign", "false")
        _git(self.root, "add", "-A")
        _git(self.root, "commit", "--quiet", "-m", "fixture")
        self.base_head = self.rev("HEAD")

    # -- helpers ---------------------------------------------------------- #

    def rev(self, ref: str) -> str:
        return _git(self.root, "rev-parse", ref).stdout.strip()

    def read(self, relative: str) -> str:
        return (self.root / relative).read_text(encoding="utf-8", newline="")

    def status(self) -> str:
        return _git(self.root, "status", "--porcelain").stdout

    def commit_files(self) -> list[str]:
        out = _git(self.root, "show", "--name-only", "--format=", "HEAD").stdout
        return [line.strip() for line in out.splitlines() if line.strip()]

    def tag_names(self) -> list[str]:
        out = _git(self.root, "tag", "--list").stdout
        return [line.strip() for line in out.splitlines() if line.strip()]

    def object_type(self, ref: str) -> str:
        return _git(self.root, "cat-file", "-t", ref).stdout.strip()

    def run_main(self, *argv: str) -> tuple[int, str, str]:
        stdout = io.StringIO()
        stderr = io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = bump_version.main(list(argv))
        return code, stdout.getvalue(), stderr.getvalue()

    def dirty_unrelated_files(self) -> None:
        """A staged tracked modification plus an untracked file, both unrelated."""
        (self.root / "README.md").write_text("# evoxc\n\nEdited by hand.\n", encoding="utf-8")
        _git(self.root, "add", "README.md")  # staged: must NOT ride along
        (self.root / "notes.txt").write_text("scratch\n", encoding="utf-8")

    def assert_hf_untouched(self) -> None:
        self.assertEqual(self.read("evoxc_hf/pyproject.toml"), FIXTURE_HF_PYPROJECT)
        self.assertNotIn("evoxc_hf/pyproject.toml", self.commit_files())


class FullBumpTests(RepoTestCase):
    def test_yes_no_push_commits_exactly_the_bumped_files(self):
        self.dirty_unrelated_files()

