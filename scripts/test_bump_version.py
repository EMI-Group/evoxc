class PyprojectPatchTests(unittest.TestCase):
    def test_changes_only_project_version(self):
        updated, edits = bump_version.patch_pyproject(FIXTURE_PYPROJECT, "0.2.0")
        self.assertIn('[project]\nname = "evoxc"\nversion = "0.2.0"\n', updated)
        self.assertEqual(
            edits, [bump_version.Edit("[project].version", "0.1.0", "0.2.0")]
        )
        # Everything else is byte-identical.
        self.assertIn('requires-python = ">=3.11"', updated)
        self.assertIn('version = "9.9.9"', updated)  # unrelated [tool.unrelated]
        self.assertIn('dev = ["pytest>=7"]', updated)
        self.assertIn('members = ["evoxc_hf"]', updated)
        self.assertEqual(len(updated.splitlines()), len(FIXTURE_PYPROJECT.splitlines()))

    def test_same_version_is_a_noop(self):
        updated, edits = bump_version.patch_pyproject(FIXTURE_PYPROJECT, "0.1.0")
        self.assertEqual(updated, FIXTURE_PYPROJECT)
        self.assertEqual(edits, [])

    def test_is_idempotent(self):
        once, _ = bump_version.patch_pyproject(FIXTURE_PYPROJECT, "0.2.0")
        twice, edits = bump_version.patch_pyproject(once, "0.2.0")
        self.assertEqual(twice, once)
        self.assertEqual(edits, [])

    def test_preserves_crlf_line_endings(self):
        text = FIXTURE_PYPROJECT.replace("\n", "\r\n")
        updated, _ = bump_version.patch_pyproject(text, "0.2.0")
        self.assertIn('version = "0.2.0"', updated)
        self.assertNotIn("\n", updated.replace("\r\n", ""))
        self.assertEqual(updated.count("\r\n"), text.count("\r\n"))

    def test_missing_project_version_raises(self):
        with self.assertRaises(bump_version.BumpError):
            bump_version.patch_pyproject('[project]\nname = "evoxc"\n', "0.2.0")


