class BuildAndWriteTests(unittest.TestCase):
    def test_build_patches_skips_missing_files_with_a_warning(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "pyproject.toml").write_text(FIXTURE_PYPROJECT, encoding="utf-8")
            stderr = io.StringIO()
            with contextlib.redirect_stderr(stderr):
                patches = bump_version.build_patches(root, "0.2.0")
            self.assertEqual([patch.path for patch in patches], [Path("pyproject.toml")])
            self.assertTrue(patches[0].changed)
            self.assertIn("warning:", stderr.getvalue())

    def test_write_patches_keeps_crlf_on_disk(self):
        original = FIXTURE_PYPROJECT.replace("\n", "\r\n")
        updated, edits = bump_version.patch_pyproject(original, "0.2.0")
        patch = bump_version.FilePatch(Path("pyproject.toml"), original, updated, edits)
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "pyproject.toml").write_bytes(original.encode("utf-8"))
            written = bump_version.write_patches(root, [patch])
            self.assertEqual(written, [Path("pyproject.toml")])
            data = (root / "pyproject.toml").read_bytes().decode("utf-8")
        self.assertIn('version = "0.2.0"', data)
        self.assertNotIn("\n", data.replace("\r\n", ""))

    def test_write_patches_skips_unchanged_files(self):
        patch = bump_version.FilePatch(
            Path("pyproject.toml"), FIXTURE_PYPROJECT, FIXTURE_PYPROJECT, []
        )
        with tempfile.TemporaryDirectory() as tmp:
            self.assertEqual(bump_version.write_patches(Path(tmp), [patch]), [])


